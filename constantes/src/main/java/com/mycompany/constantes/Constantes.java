package com.mycompany.constantes;

/**
 *
 * @author wilberV
 */
public class Constantes {

    public static void main(String[] args) {
        
        /* Constantes son variables que no varia Y simple mente 
           hay que poner (final) delante de cualquier tipo de Dato
        */
       byte numero;
       
       numero = 20;// Valor incial. 
       numero = 22;// Valor final Salida real 22.
       
       final byte numeroUnico;
       numeroUnico = 20;// Salida unica.
       
        System.out.println(numero);
        System.out.println(numeroUnico);
       
       
       
    }
}
