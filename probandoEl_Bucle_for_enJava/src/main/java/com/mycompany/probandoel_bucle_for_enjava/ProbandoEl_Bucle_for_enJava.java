
package com.mycompany.probandoel_bucle_for_enjava;


public class ProbandoEl_Bucle_for_enJava {

    public static void main(String[] args) {
        
        int n1,n2 = 1 , total = 0;
        
        
        for (n1 = 1 ; n2<=12; n2++){
            
            total = n1 * n2;
        
          System.out.println(n1+" x "+n2+" = "+total);
          n1++;
        }
        
    }
}
